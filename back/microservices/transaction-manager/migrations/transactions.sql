CREATE TABLE IF NOT EXISTS source (
	id TEXT NOT NULL,
	userId INTEGER NOT NULL,

	title TEXT NOT NULL,
	filename TEXT NOT NULL,
	kepubify BOOLEAN NOT NULL DEFAULT FALSE,
	toCLoud BOOLEAN NOT NULL DEFAULT FALSE,
	
	configKey TEXT,

	isRtl BOOLEAN NOT NULL DEFAULT FALSE,
	"join" BOOLEAN NOT NULL DEFAULT FALSE,

	status TEXT NOT NULL DEFAULT 'pending_upload',
	errorMsg TEXT,
	size INTEGER,
	isFile BOOLEAN NOT NULL DEFAULT TRUE,
	createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	completedAt DATETIME,

	parentId TEXT,
	position INTEGER NOT NULL DEFAULT 0,
	isResult BOOLEAN NOT NULL DEFAULT FALSE,

	PRIMARY KEY (id, userId),
	FOREIGN KEY (parentId, userId) 
		REFERENCES source(id, userId)
		ON UPDATE CASCADE
		ON DELETE CASCADE,
	FOREIGN KEY (configKey)
		REFERENCES config(hash)
		ON UPDATE NO ACTION
		ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS config (
	hash TEXT PRIMARY KEY,
	data TEXT NOT NULL,

	createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	lastUsed DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_source_user_parent_created
	ON source (userId, parentId, createdAt DESC);
